/**
 * `pnpm build:ui` (runs this with --write): bundles the dashboard view (ui/dashboard) into one self-contained HTML
 * document and writes it as a string constant to src/ui/dashboard-html.generated.ts, so the
 * Worker (wrangler deploy), stdio (tsx) and the tests all import the same HTML with no build
 * step of their own. tests/dashboard-ui.test.ts fails when the committed file is out of date.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = new URL('../', import.meta.url);
const TEMPLATE = new URL('ui/dashboard/index.html', ROOT);
const ENTRY = new URL('ui/dashboard/main.ts', ROOT);
export const GENERATED_FILE = new URL('src/ui/dashboard-html.generated.ts', ROOT);
const SCRIPT_SLOT = '/*DASHBOARD_SCRIPT*/';

/** Escapes everything outside printable ASCII, so the file has one fixed encoding. */
function asciiOnly(text: string): string {
  return text.replace(
    /[^\n\x20-\x7e]/g,
    (char) => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`,
  );
}

export async function buildDashboardHtml(): Promise<string> {
  const bundle = await build({
    entryPoints: [fileURLToPath(ENTRY)],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    charset: 'ascii',
    logLevel: 'silent',
  });
  const script = bundle.outputFiles[0]?.text.trim();
  if (!script) throw new Error('esbuild produced no output');
  if (/<\/script|<!--/i.test(script)) {
    throw new Error('the bundled script contains a sequence that would end the inline script');
  }
  // The same output on every checkout, whatever line endings git wrote.
  const template = (await readFile(TEMPLATE, 'utf8')).replace(/\r\n/g, '\n');
  if (template.split(SCRIPT_SLOT).length !== 2) throw new Error('template needs one script slot');
  return template.replace(SCRIPT_SLOT, () => script);
}

export function generatedModule(html: string): string {
  return (
    '// Generated by `pnpm build:ui` from ui/dashboard. Do not edit by hand.\n' +
    `export const DASHBOARD_HTML = ${asciiOnly(JSON.stringify(html))};\n`
  );
}

if (process.argv.includes('--write')) {
  const html = await buildDashboardHtml();
  await writeFile(GENERATED_FILE, generatedModule(html));
  process.stdout.write(`Wrote ${fileURLToPath(GENERATED_FILE)} (${html.length} characters)\n`);
}
